// UI sprite header (0x8c bytes each).
struct UiSprite {
    u8 unk00[0x8c];
};

// Item/skill list screen: its sprite pool and the state words cleared on init.
struct ListScreen {
    u8 unk0000[0x20];
    UiSprite sprites[0x42];     // 0x20: rows 0-9 icons, 10-59 columns, 60-65 buttons
    u32 word2438;               // 0x2438
    u32 word243c;               // 0x243c
    u32 word2440;               // 0x2440
    f32 word2444;               // 0x2444 (0.0f)
    u16 half2448;               // 0x2448
    u16 half244a;               // 0x244a
    u8 unk244c[4];
    s16 rowId[10];              // 0x2450
    u16 rowCount[10];           // 0x2464
    f32 rowValue[10];           // 0x2478 (0.0f)
    s16 rowExtra[10];           // 0x24a0
};

